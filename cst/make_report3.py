TEXT_W = Cm(16.5)   # ширина полосы набора: 21 − 2,5 − 2 см


def eq(tokens, num):
    """Формула по ГОСТ 2.105/7.32: сама формула по центру строки, номер в круглых скобках у правого поля.
    tokens — список (текст, стиль): 'n' прямой, 'i' курсив (скаляры), 'b' полужирный курсив (векторы),
    'sub'/'subi' нижний индекс (прямой/курсив), 'sup' верхний индекс, 'op' знак суммы крупно."""
    p = d.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.space_before = Pt(6); p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.first_line_indent = Cm(0)
    ts = p.paragraph_format.tab_stops
    ts.add_tab_stop(Cm(TEXT_W.cm / 2), WD_TAB_ALIGNMENT.CENTER); ts.add_tab_stop(TEXT_W, WD_TAB_ALIGNMENT.RIGHT)
    p.add_run("\t")
    for text, stl in tokens:
        r = p.add_run(text); r.font.name = FONT; r.font.size = Pt(12)
        if stl in ("i", "subi"):
            r.italic = True
        if stl == "b":
            r.bold = True; r.italic = True
        if stl in ("sub", "subi"):
            r.font.subscript = True
        if stl == "sup":
            r.font.superscript = True
        if stl == "op":
            r.font.size = Pt(16)
    p.add_run(f"\t({num})")
    return p


# часто используемые куски
def TAU(idx):   # τ с индексом (прямой индекс: tn, rk, nk — номера элементов)
    return [("τ", "i"), (idx, "sub")]


def R(idx=None, bold=True):   # вектор r (полужирный курсив) с индексом
    return [("r", "b")] + ([(idx, "sub")] if idx else [])



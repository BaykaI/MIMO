    para.add_run("\t")
    for txt, s in tokens:
        r = para.add_run(txt); r.font.size = Pt(18 if s == "op" else 14)
        r.italic = s in ("i", "b"); r.bold = s == "b"; r.font.subscript = s == "sub"; r.font.superscript = s == "sup"
    para.add_run(f"\t({EQ[0]})")
    return EQ[0]



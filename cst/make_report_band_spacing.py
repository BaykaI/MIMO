def n(v, nd=1):
    """число в тексте: десятичная запятая, отрицательное словом «минус»"""
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "н/д"
    s = f"{abs(v):.{nd}f}".replace(".", ",")
    return ("минус " + s) if v < -0.5 * 10 ** (-nd) else s


def t(v, nd=1):
    """число в таблице: десятичная запятая, знак минус"""
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "–"
    return f"{v:.{nd}f}".replace(".", ",").replace("-", "−")



def n(v, nd=1):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "н/д"
    s = f"{abs(v):.{nd}f}".replace(".", ",")
    return ("минус " + s) if v < -0.5 * 10 ** (-nd) else s


def t(v, nd=1):
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "–"

def table(title, header, rows, widths):
    TAB[0] += 1
    cap = p(f"Таблица {TAB[0]} – {title}", indent=False, align=WD_ALIGN_PARAGRAPH.LEFT, keep=True)
    tb = doc.add_table(rows=1, cols=len(header)); tb.style = "Table Grid"; tb.alignment = WD_TABLE_ALIGNMENT.CENTER
    tb.autofit = False

    def cell(c, txt):
        c.text = ""; q = c.paragraphs[0]; q.paragraph_format.first_line_indent = Cm(0); q.paragraph_format.line_spacing = 1.0
        q.alignment = WD_ALIGN_PARAGRAPH.CENTER; r = q.add_run(str(txt)); r.font.size = Pt(12)
    for i, hd in enumerate(header):
        cell(tb.rows[0].cells[i], hd)
    trPr = tb.rows[0]._tr.get_or_add_trPr(); th = OxmlElement("w:tblHeader"); th.set(qn("w:val"), "true"); trPr.append(th)
    for row in rows:
        cs = tb.add_row().cells
        for i, v in enumerate(row):
            cell(cs[i], v)
    for row in tb.rows:
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return TAB[0]


def eq(tokens):
    EQ[0] += 1
    para = doc.add_paragraph(); para.paragraph_format.first_line_indent = Cm(0)
    para.paragraph_format.space_before = Pt(6); para.paragraph_format.space_after = Pt(6)
    ts = para.paragraph_format.tab_stops; ts.add_tab_stop(Cm(8.25), WD_TAB_ALIGNMENT.CENTER); ts.add_tab_stop(Cm(16.5), WD_TAB_ALIGNMENT.RIGHT)
    para.add_run("\t")
    for txt, s in tokens:
        r = para.add_run(txt); r.font.size = Pt(14); r.font.name = "Times New Roman"
        r.italic = s in ("i", "b"); r.bold = s == "b"; r.font.subscript = s == "sub"
    para.add_run(f"\t({EQ[0]})")
    return EQ[0]



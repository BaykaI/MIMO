def p(text, indent=True, align=None, keep=False):
    para = doc.add_paragraph(); pf = para.paragraph_format
    pf.first_line_indent = Cm(1.25 if indent else 0); pf.line_spacing = 1.5; pf.space_after = Pt(0); pf.space_before = Pt(0)
